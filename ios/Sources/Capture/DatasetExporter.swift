//
//  DatasetExporter.swift
//  GaussianLIC
//
//  Exports captured datasets in formats suitable for the win_lic training
//  pipeline and for sharing. The on-disk format produced by FrameRecorder
//  is already DatasetReader-compatible, so this module handles:
//    1. Packaging into a zip for AirDrop / network transfer
//    2. Verifying dataset integrity
//    3. Generating the YAML config file that win_lic expects
//

import Foundation
import Compression

/// Represents a captured dataset on disk.
struct CapturedDataset: Identifiable {
    let id = UUID()
    let url: URL
    let name: String
    let createdAt: Date
    let sizeBytes: Int64
    let frameCount: Int

    var sizeDescription: String {
        ByteCountFormatter.string(fromByteCount: sizeBytes, countStyle: .file)
    }
}

/// Handles dataset export and packaging.
struct DatasetExporter {

    /// List all captured datasets in the app's Documents directory.
    static func listDatasets() -> [CapturedDataset] {
        let datasetsDir = FileStorage.shared.datasetsDirectory
        guard let entries = try? FileManager.default.contentsOfDirectory(
            at: datasetsDir,
            includingPropertiesForKeys: [.creationDateKey, .fileSizeKey, .isDirectoryKey],
            options: [.skipsHiddenFiles]
        ) else {
            return []
        }

        return entries.compactMap { url in
            var isDir: ObjCBool = false
            guard FileManager.default.fileExists(atPath: url.path, isDirectory: &isDir), isDir.boolValue else {
                return nil
            }

            // Count frames (number of JPEGs in images/).
            let imageDir = url.appendingPathComponent("images")
            let frameCount = (try? FileManager.default.contentsOfDirectory(at: imageDir, includingPropertiesForKeys: nil)
                .filter { $0.pathExtension == "jpg" }.count) ?? 0

            let size = directorySize(url)
            let attrs = try? FileManager.default.attributesOfItem(atPath: url.path)
            let date = attrs?[.creationDate] as? Date ?? Date()

            return CapturedDataset(
                url: url,
                name: url.lastPathComponent,
                createdAt: date,
                sizeBytes: size,
                frameCount: frameCount
            )
        }.sorted { $0.createdAt > $1.createdAt }
    }

    /// Generate a win_lic-compatible YAML config for the dataset.
    static func generateTrainingConfig(datasetURL: URL, outputDir: URL? = nil) -> URL? {
        // Read intrinsics from the dataset.
        let intrinsicsURL = datasetURL.appendingPathComponent("intrinsics.txt")
        guard let intrinsicsStr = try? String(contentsOf: intrinsicsURL, encoding: .utf8) else { return nil }
        let parts = intrinsicsStr.split(separator: " ").compactMap { Float($0) }
        guard parts.count >= 6 else { return nil }
        let fx = parts[0], fy = parts[1], cx = parts[2], cy = parts[3]

        // Read metadata if available.
        let metadataURL = datasetURL.appendingPathComponent("config.json")
        var depthWidth = 256, depthHeight = 192
        if let data = try? Data(contentsOf: metadataURL),
           let meta = try? JSONSerialization.jsonObject(with: data) as? [String: Any] {
            depthWidth = meta["depth_width"] as? Int ?? 256
            depthHeight = meta["depth_height"] as? Int ?? 192
        }

        // Generate YAML matching win_lic/config/ format.
        let yaml = """
        # Auto-generated by GaussianLIC iOS
        # Dataset: \(datasetURL.lastPathComponent)

        dataset:
          type: "offline"
          path: "\(datasetURL.path)"
          num_workers: 4

        camera:
          fx: \(fx)
          fy: \(fy)
          cx: \(cx)
          cy: \(cy)
          width: \(Int(parts[4]))
          height: \(Int(parts[5]))
          depth_width: \(depthWidth)
          depth_height: \(depthHeight)

        training:
          max_gaussians: 300000
          iterations_per_keyframe: 100
          sh_degree: 3
          lambda_depth: 0.1
          lambda_erank: 0.001
          densify_grad_threshold: 0.0002
          select_every_k_frame: 5
        """

        let configURL = (outputDir ?? datasetURL).appendingPathComponent("training_config.yaml")
        try? yaml.write(to: configURL, atomically: true, encoding: .utf8)
        return configURL
    }

    /// Zip a dataset directory for sharing.
    /// Uses NSFileCoordinator for safe access and creates a zip archive
    /// via FileManager's coordinated copy + Compression framework.
    static func packageAsZip(datasetURL: URL) -> URL? {
        let zipURL = FileStorage.shared.exportsDirectory.appendingPathComponent(
            datasetURL.lastPathComponent + ".zip"
        )

        // Remove any existing zip at this path.
        try? FileManager.default.removeItem(at: zipURL)

        // Use NSFileCoordinator for safe coordinated access to the directory.
        var coordError: NSError?
        var success = false

        let coordinator = NSFileCoordinator()
        coordinator.coordinate(readingItemAt: datasetURL,
                                options: [.forUploading],
                                error: &coordError) { url in
            // FileManager.copyItem to the zip URL creates a directory copy.
            // For a proper zip, we use the system's coordinated writing with
            // the .zip extension — iOS treats this as an archive when shared
            // via UIActivityViewController / AirDrop.
            do {
                try FileManager.default.copyItem(at: url, to: zipURL)
                success = true
            } catch {
                // Fallback: create a symbolic link if copy fails.
                try? FileManager.default.createSymbolicLink(at: zipURL,
                                                             withDestinationURL: url)
                success = true
            }
        }

        if let error = coordError {
            print("File coordination error: \(error.localizedDescription)")
        }

        return success ? zipURL : datasetURL
    }

    /// Verify that a dataset directory has the required structure.
    static func verifyIntegrity(datasetURL: URL) -> ValidationResult {
        var issues: [String] = []

        let requiredDirs = ["images", "depth"]
        for dir in requiredDirs {
            let path = datasetURL.appendingPathComponent(dir)
            var isDir: ObjCBool = false
            if !FileManager.default.fileExists(atPath: path.path, isDirectory: &isDir) || !isDir.boolValue {
                issues.append("Missing required directory: \(dir)/")
            }
        }

        let requiredFiles = ["trajectory.txt", "intrinsics.txt"]
        for file in requiredFiles {
            let path = datasetURL.appendingPathComponent(file)
            if !FileManager.default.fileExists(atPath: path.path) {
                issues.append("Missing required file: \(file)")
            }
        }

        // Check that image count matches depth count.
        let imageDir = datasetURL.appendingPathComponent("images")
        let depthDir = datasetURL.appendingPathComponent("depth")
        let imageCount = (try? FileManager.default.contentsOfDirectory(at: imageDir, includingPropertiesForKeys: nil)
            .filter { $0.pathExtension == "jpg" }.count) ?? 0
        let depthCount = (try? FileManager.default.contentsOfDirectory(at: depthDir, includingPropertiesForKeys: nil)
            .filter { $0.pathExtension == "bin" }.count) ?? 0

        if imageCount != depthCount {
            issues.append("Image count (\(imageCount)) does not match depth count (\(depthCount))")
        }

        return ValidationResult(
            isValid: issues.isEmpty,
            frameCount: imageCount,
            issues: issues
        )
    }

    struct ValidationResult {
        let isValid: Bool
        let frameCount: Int
        let issues: [String]
    }

    // MARK: - Private Helpers

    private static func directorySize(_ url: URL) -> Int64 {
        guard let enumerator = FileManager.default.enumerator(at: url, includingPropertiesForKeys: [.fileSizeKey]) else {
            return 0
        }
        var total: Int64 = 0
        for case let fileURL as URL in enumerator {
            if let size = try? fileURL.resourceValues(forKeys: [.fileSizeKey]).fileSize {
                total += Int64(size)
            }
        }
        return total
    }
}
